// Command genschema writes the schema liquibase-runner produces from db/changelog as plain DDL,
// for sqlc to read. `task gen` runs it; it needs Docker.
package main

import (
	"context"
	"fmt"
	"os"

	"github.com/JorisJonkers-dev/identity/internal/platform/pg/pgtest"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genschema <out.sql>")
		os.Exit(2)
	}
	schema, err := pgtest.Schema(context.Background())
	if err != nil {
		fmt.Fprintf(os.Stderr, "genschema: %v\n", err)
		os.Exit(1)
	}
	header := "-- Generated by `task gen` from db/changelog through liquibase-runner. Do not edit.\n\n"
	if err := os.WriteFile(os.Args[1], []byte(header+schema), 0o644); err != nil { //nolint:gosec // a committed source file, read by everyone.
		fmt.Fprintf(os.Stderr, "genschema: %v\n", err)
		os.Exit(1)
	}
}
